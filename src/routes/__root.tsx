/** Page-load curtain + per-route fade, keeping navigation cinematic. */
function PageTransition({ children }: { children: ReactNode }) {
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  const [loaded, setLoaded] = useState(false);
  const [visible, setVisible] = useState(true);

  useEffect(() => {
    const t = window.setTimeout(() => setLoaded(true), 60);
    return () => window.clearTimeout(t);
  }, []);

  useEffect(() => {
    setVisible(false);
    window.scrollTo({ top: 0, behavior: "auto" });
    const t = window.setTimeout(() => setVisible(true), 40);
    return () => window.clearTimeout(t);
  }, [pathname]);

  return (
    <>
      <div
        aria-hidden
        className="pointer-events-none fixed inset-0 z-[60] bg-background transition-opacity duration-1000 [transition-timing-function:var(--ease-cinema)]"
        style={{ opacity: loaded ? 0 : 1 }}
      />
      <div
        className="transition-opacity duration-700 [transition-timing-function:var(--ease-cinema)]"
        style={{ opacity: visible ? 1 : 0 }}
      >
        {children}
      </div>
    </>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  const isContactPage = pathname === "/contact";

  return (
    <QueryClientProvider client={queryClient}>
      <Nav />
      <main id="main">
        <PageTransition>
          {/* Required: nested routes render here. */}
          <Outlet />
        </PageTransition>
      </main>
      {!isContactPage && <Footer />}
    </QueryClientProvider>
  );
}

